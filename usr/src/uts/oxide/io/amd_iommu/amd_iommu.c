static void
amd_iommu_startup(void)
{
	if (amd_iommu_intrmap_disabled())
		return;
	amd_iommu_segment_t *segment = zen_iommu_segment;

	/*
	 * Add interrupt remapping tables for the IOAPICs.  Entries for PCIe
	 * endpoints and bridges are added elsewhere.
	 */
	for (int i = 0; i < ARRAY_SIZE(apic_io_iommu_devid); i++) {
		uint16_t device_id = apic_io_iommu_devid[i];
		amd_iommu_intr_remap_tbl_t *irt;
		if (device_id == 0)
			break;
		irt = amd_iommu_intr_remap_tbl_alloc(device_id);
		mutex_enter(&segment->ais_lock);
		intrmap_segment_add_irt(segment, device_id, irt);
		mutex_exit(&segment->ais_lock);
	}
	/*
	 * We may now enable all of the IOMMUs in the segment.
	 */
	mutex_enter(&segment->ais_lock);
	for (amd_iommu_t *iommu = list_head(&segment->ais_iommus);
	    iommu != NULL;
	    iommu = list_next(&segment->ais_iommus, iommu)) {
		mutex_enter(&iommu->ai_ctl_lock);
		amd_iommu_mmio_reg_ctl_t ctl = amd_iommu_read_ctl(iommu);
		ctl.aimr_ctl_en = 1;
		amd_iommu_write_ctl(iommu, ctl);
		mutex_exit(&iommu->ai_ctl_lock);
	}
	segment->ais_running = true;
	mutex_exit(&segment->ais_lock);
	amd_iommu_invalidate_all_segment(segment);
	amd_iommu_intrmap_os_startup();
}

