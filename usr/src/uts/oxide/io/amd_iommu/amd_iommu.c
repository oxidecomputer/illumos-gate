/*
 * AMD IOMMU
 * =========
 * This is the code to support the AMD IOMMU for the Oxide architecture.
 * The IOMMU is documented in AMD publication 48882, and at the time of writing,
 * version 3.11 is current.
 *
 * Overview
 * --------
 * The IOMMU is capable of doing several things:
 *
 *  - It can virtualize the host physical address space as seen by a device
 *  - It can remap interrupts generated by a device, and direct them to a
 *    specific CPU or logical group of CPUs, at a specific vector
 *  - It can handle direct delivery of interrupts into a virtual machine by
 *    manipulating the guest's virtual APIC state
 *  - It can present a "second level" virtual IOMMU so that it can be
 *    virtualized itself.
 *  - It can filter undesirable _types_ of interrupts from devices, preventing
 *    a misconfigured or malicious device from affecting the system.  For
 *    example, it can block NMIs and filter SMIs.
 *
 * From this rich suite of functionality, the Oxide architecture presently only
 * supports interrupt remapping and SMI filtering.  We primarily use this to
 * support device interrupt delivery to high-numbered CPUs on machines with
 * large core-counts: in particular, when considering PCIe devices, neither MSI
 * nor MSI-X on x86 directly support the full width of the x2APIC ID space, but
 * rather limit the destination APIC ID field to 8 bits.  However, with
 * appropriate configuration the IOMMU supports a full 32-bit x2APIC ID for an
 * interrupt's destination: thus, to direct interrupts to those CPUs, we remap
 * them through the IOMMU.
 *
 * How The IOMMU Remaps Interrupts
 * -------------------------------
 * At a high level, an IOMMU interposes on interrupt-generating transactions
 * coming from devices so that, when a device attempts to generate an interrupt,
 * the IOMMU intercedes and looks up the originating device in a _Device Table_,
 * and then uses information in the interrupt request as an index into a
 * per-device _Interrupt Remapping Table_ that describes where the interrupt
 * should be directed, what vector and type it should be, and so on.
 *
 * As mentioned, each IOMMU is configured to point to a _Device Table_, indexed
 * by a _Device ID_, that says what to do with accesses for a particular device.
 * When interrupt messages arrive at an IOMMU, the device table is indexed by
 * the Device ID of the device that generated the interrupt message: for PCIe
 * devices, this is a 16-bit PCI BDF; for external devices connected to an
 * IOAPIC and for internal devices, the DeviceID is synthesized to look like a
 * BDF.  This synthesized ID is derived from the internal topology of the SoC.
 * Note that this implies an impedance mismatch with respect to naming and PCIe:
 * since the device table is indexed by BDF, when it comes to PCIe devices, what
 * the IOMMU refers to as a "device" is really a PCI(e) _function_.
 *
 * The indexed _Device Table Entry_ (DTE) contains a set of control bits
 * defining if and how interrupt remapping should be handled, and a pointer to
 * the base of a per-device _Interrupt Remapping Table_ (IRT).  If remapping is
 * enabled, the interrupt is looked up in the IRT; the index into the IRT is
 * derived from data bits 10:0 of the MSI(-X) interrupt message or redirection
 * table entry in the IOAPIC.  The address in the MSI interrupt message is
 * ignored.
 *
 * The interrupt table entry (IRTE), in turn, contains information about the
 * remapped interrupt and where it will be delivered, including:
 *
 *  - What kind of interrupt should be generated (Fixed, NMI, etc)
 *  - The APIC ID of the destination logical processor
 *  - The remapped interrupt's vector number
 *  - Trigger and Destination Mode, etc
 *
 * At a slightly lower level, IOMMUs are represented as PCI devices, and there
 * are multiple such devices on a fabric; for Milan, Genoa, and Turin, there are
 * four per SoC.
 *
 * At the implementation level, each SoC has some number of integrated IO hubs,
 * each of which has one or more integrated IOMMU "L1"s, connected to PCIe
 * cores, NBIFs, and IO aggregators, that monitor device traffic.  If the IOMMU
 * is enabled, the L1s forward memory and interrupt accesses on to a paired
 * IOMMU "L2", which may or may not be associated with the same IOHC, but will
 * be associated with _some_ IOHC.  Empirically, we have observed that what we
 * colloquially refer to as the "large" type IOHCs have both L1 and L2 IOMMU
 * interfaces, whereas the "small" type IOHCs have only the L1 interfaces.
 *
 * From a programming perspective, we interact with an IOMMU through a block of
 * "MMIO registers", though we can interact with these via SMN, not only through
 * memory-mapped IO.  The MMIO register blocks for each IOMMU are in bijection
 * with the L2 interfaces mentioned above, and are associated with large IOHCs.
 *
 * Pictorially, the relationships between components appears as follows:
 *
 *                  +------------+         +------------+
 * +----------+     |  IOHC (L)  |         |  IOHC (L)  |
 * | IOHC (S) |     |  +---------+   ...   |  +---------+
 * |  +-------+     |  | IOMMUL1s|         |  | IOMMUL1s|
 * |  |IOMMUL1|-\   |  +---------+         |  +---------+
 * +--+-------+  \--|  | IOMMUL2 |         |  | IOMMUL2 |
 *                  |  +---------+         |  +---------+
 *                  |  |IOMMUMMIO|         |  |IOMMUMMIO|
 *                  +--+---------+         +--+---------+
 *                       |                   /
 *                       |     /------------/
 *                       |    /
 *                       |   /
 *                 +-----------+    +-------------+
 *                 |           |----|IRT (per dev)|
 *                 |           |    +-------------+
 *                 |           |
 *                 |  Device   |    +-------------+
 *                 |   Table   |----|IRT (per dev)|
 *                 |           |    +-------------+
 *                 |(Shared by |
 *                 |all IOMMUs |           .
 *                 |  on this  |           .
 *                 | segment)  |           .
 *                 |           |
 *                 |           |    +-------------+
 *                 |           |----|IRT (per dev)|
 *                 +-----------+    +-------------+
 *
 * Note that we share the device table across all IOMMUs on a PCI segment, as
 * the BDF space covers all devices, including IOAPICs, is thus only unique per
 * segment, and architecturally, all devices attached to an IOMMU must be on the
 * same PCIe segment.  While we do not strictly need to share the device table,
 * there is no reason not to, as the IOMMUs within a SoC are already sharing the
 * device space, and allocating one covering the entire DeviceID space per IOMMU
 * would be wasteful.  Note, however, that nothing prevents an IOMMU from
 * speculatively caching entries for devices that are not downstream of it, and
 * we do not know the effects this might have on e.g. peer-to-peer transactions
 * (hence one reason we invalidate DTEs on all IOMMUs presently; see below).
 *
 * Note that AMD does not use our segment-oriented terminology.  We adopt it as
 * that provides a conceptually intuitive framing for the relationships between
 * components, and architecturally, all devices attached to an IOMMU must
 * implicitly be on the same segment.
 *
 * ### Addressing Logical Processors (LPs) with APIC IDs >254
 *
 * Using the interrupt remapping capabilities of the IOMMU can permit directing
 * device interrupts to logical processors with LAPIC ID numbers >254.  The
 * challenge is that the data formats programmed into an interrupt redirection
 * table record in an IOAPIC, and into the MSI data and address pairs for PCI
 * devices, only permit an 8-bit APIC ID; a limitation inherited by MSI-X.  But
 * entries in the device table allow us to specify use of an extended form of
 * interrupt remapping table entries, which supports giving a full 32-bit
 * destination x2APIC ID for the remapped interrupt.
 *
 * Note that it is not necessary to have more than 254 logical processors in a
 * system to have a LAPIC ID >254: consider a 2P system, in which the system
 * may accommodate processors with up to some number of logical processors
 * greater than 256, but with substantially fewer (say, 32 cores and 64 LPs).
 * Then the system may number cores for the processor in the second socket
 * starting from the maximum number of LPs per socket.
 *
 * That is, if each socket could accommodate a 128C/256T CPU, but a 32C/64T
 * CPU was installed in each socket, then LPs on the package in the first
 * socket might be numbered [0,..,64), LPs in the second socket may be numbered
 * [256,..,320), and the machine has a total of 128 LPs.
 *
 * ### Addressing Interrupts Generated _by the IOMMU_ to High ID CPUs
 *
 * As mentioned earlier, the IOMMU itself presents itself to systems software as
 * a PCI device.  Importantly, it can generate interrupts when, for example, its
 * event log overflows, it encounters some kind of exceptional condition, or a
 * command completes.  It is important to note, however, that interrupts
 * generated by the IOMMU are not remapped by the IOMMU.
 *
 * That, and the ability to use the IOMMU in multi-segment systems (or
 * single-segment systems with high core-count CPUs) raises a question: if the
 * IOMMU is architecturally prohibited from remapping interrupts that it
 * generates itself, and it is programmed like a PCI device using MSI or MSI-X,
 * and the destination APIC ID for MSI/MSI-X on x86 is architecturally limited
 * to 8 bits, then how does it direct those interrupts to CPUs with APIC IDs
 * that do not fit into 8 bits?
 *
 * To address this, the IOMMU can be specially configured via a 64-bit register
 * that is conceptually similar to MSI data and address pairs, but that supports
 * a 32-bit x2APIC ID for the destination CPU, as well as an 8-bit vector number
 * and 1 bit destination mode.  See the "XT IOMMU General Interrupt Control
 * Register" in the IOMMU specification for reference.  Note that this mechanism
 * is unique to the IOMMU, and exists outside of the other standard mechanisms
 * for specifying an interrupt's destination.
 *
 * ### Caveat: the 8259A
 *
 * In the Oxide architecture, we do not use the legacy 8259A ("Programmable
 * Interrupt Controller" [PIC]), so this is of little concern to us.  But
 * more broadly, a caveat to be aware of is that interrupts delivered through
 * the PIC are not remapped by the IOMMU.  Usually such interrupts are sent
 * directly to the bootstrap processor via its LINT0 pin.
 *
 * There are some esoteric configurations where PIC-routed interrupts can be
 * delivered indirectly through an IOAPIC in "virtual wire mode".  In these
 * configurations, one can program the redirection table entry for the IOAPIC
 * pin connected to the PIC to send to some CPU other than the BSP, which could
 * theoretically vector through the IOMMU, but this is rarely done; this
 * configuration exists largely to support legacy uniprocessor software, and the
 * AMD IOMMU specification states explicitly that PIC interrupts are not
 * remapped.
 *
 * Interrupt Remapping in the Oxide Architecture
 * ---------------------------------------------
 * The Oxide architecture unconditionally uses the x2APIC, and each logical
 * processor has its own LAPIC timer, so CPUs with high LAPIC IDs are usable
 * without additional support: they can send and receive IPIs, participate in
 * cross-calls, and can generate and receive timer interrupts for scheduling
 * and preemption.  We use the interrupt remapping via the IOMMU so that
 * interrupts generated by peripheral devices can be directed to those CPUs, as
 * well.
 *
 * Further, the IOMMU also provides mechanisms allowing us to suppress devices
 * sending SMI, INIT, SIPI, and NMI interrupts, as devices should never send
 * those.  Of that set, only NMIs are of interest to us in any way, and those
 * should only be sent as IPIs or generated from the FCH.  IPIs inherently
 * bypass the IOMMU, and we have determined empirically NMIs generated from the
 * FCH bypass remapping as well.
 *
 * Oxide machines currently have exactly one PCIe segment, and a single device
 * table is shared by all IOMMUs in the system.  Except for NMIs and interrupts
 * originating from an IOMMU itself, all peripheral device interrupts are routed
 * through an IOMMU.
 *
 * For simplicity, we allocate a single device table spanning the entire 16-bit
 * BDF space and share this with all IOMMUs.  As each IOMMU has some devices
 * associated with it, and these do not vary, their use of the shared table does
 * not conflict.
 *
 * Each DTE is 256 (2^8) bits long, and there are 65536 (2^16) entries, so the
 * total space required, expressed in 8-bit bytes, is thus 2^(8-3+16) = 2^21
 * bytes, or 2MiB.  We do not use Device Table Segmentation at this time.  The
 * IOMMUs require that the device table be a physically contiguous region of
 * memory.
 *
 * Each DTE points to a unique IRT, specific to the interrupt source
 * corresponding to that DeviceID: recall that for PCIe devices, this is a
 * PCI function, not a PCI device.
 *
 * Within a given IRT, IRTEs are allocated dynamically, starting from entry 0
 * up to a limit set by the hardware and configured in the DTE.  Also, the IOMMU
 * control register has a field that selects the number of supported MSIs that
 * can only select between 512 or 2048 entries, but this is specific to Turin,
 * and defaults to 512 elsewhere.  Even though the size of the IRT can be set
 * independently, we use the bound on MSIs specified in the control register as
 * an upper bound on the size of our IRTs, and thus the per-device limit on
 * interrupt allocation.  Oxide currently sets it to 512: empirically, this far
 * exceeds the per-function requirement of any device we have actually fielded.
 *
 * The IOMMU architecturally requires that each IRT is physically contiguous,
 * and IRTEs use an extended format that is 128 bits (16 bytes) long, so 512
 * entries requires 8KiB of physical memory.  The alignment requirement is only
 * 128 bytes, but any practical allocation we make will be at least 4KiB
 * aligned, so it is simpler to just use two physically adjacent page frames,
 * aligned to a 4KiB page boundary.
 *
 * The IRT size is somewhat unfortunate, as no devices consume anywhere near
 * that number of entries.  In principle, it may be possible to share IRTs
 * between devices, but there is some complexity involved since interrupts are
 * allocated and freed individually: should we require more IRTEs than are
 * available in a given IRT, and since each DTE points to an IRT, we would have
 * to reallocate and redistribute previously allocated interrupts for the device
 * in question.  However in practice, the total number of allocated tables is
 * not that large, and it is simpler, if marginally wasteful, to give each
 * device/function its own IRT.
 *
 * Once an IRT is allocated to a device, we do not free it, even if the device
 * is later removed.  This is a small simplification based on observing that the
 * only such devices are hotplug devices, and that these are likely to be
 * reattached, that the amount of memory is small, and that we'd rather not deal
 * with a failure path when allocating in the presence of spin mutexes.
 *
 * Sending Commands to, and Receiving Events From, an IOMMU
 * --------------------------------------------------------
 * Each IOMMU supports a command buffer implementing a ring shared with the
 * host.  The host can write a command into the buffer and ring a doorbell in
 * the IOMMU by writing a tail pointer; the IOMMU will read the command,
 * interpret, and act on it (or generate an error indication of some kind).
 * Commands include directives to invalidate cached state that may have changed
 * on the host, etc: this is generally required when updating the DT or IRTEs.
 * The IOMMU can be configured to generate an interrupt when a command completes
 * or generates an error.
 *
 * Similarly, an event log ring shared with the host may be configured: the
 * IOMMU will log notable events here and can be configured to inform the host
 * via generating an interrupt, or the host may poll.  The host acknowledges
 * and dismisses events by writing to a head register on each IOMMU.  If the
 * event log is totally filled, the IOMMU stops writing events to it until it
 * is drained and re-enabled; events generated during this time are lost, though
 * this has no impact on command processing.
 *
 * Command buffers and event logs are per-IOMMU resources, not shared between
 * IOMMUs, as the device table is.
 *
 * Mutexes, Lock Ordering, and Interactions With apix
 * --------------------------------------------------
 * Many of the operations that we perform are initiated by apix: allocation,
 * mapping, and freeing of interrupts for example.  These happen while apix is
 * holding the `apic_ioapic_lock` spinlock, and so to avoid deadlocks, our
 * mutexes must spin, and cannot be adaptive.  Therefore, we initialize them
 * at high priority.
 *
 * Our lock strategy here is based on two approaches: First, implicitly: most
 * updates to IRTEs happen in response to apix operations, while apix is holding
 * the `apic_ioapic_lock` spinlock.  This is handled by apix, and it is mostly
 * opaque to us; we assume that any path called from an apix handler may be one
 * that holds that spinlock.
 *
 * But relying on apix implicitly holding a lock while we are modifying our
 * own structures is fragile: first, because apix's lock protocol is opaque to
 * us we do not necessarily know that apix _is_ holding the lock, just that it
 * _may_ be.  Furthermore, we may access our own data structures outside of
 * paths flowing through apix.  For example, DTE updates happen at startup, but
 * also in response to hotplug events, before apix allocates interrupts to the
 * affected device.  This motivates our second approach: serializing access via
 * our own mutexes.
 *
 * This naturally raises a question: if we are serializing access ourselves, why
 * worry about apix at all?  Why don't we just rely solely on our own
 * synchronization and forget about anything of the kind that apix may be doing
 * independent of us?  To a first order approximation, that is what we do.
 * However, we must still be aware of the apix lock because, as mentioned above,
 * it influences the types of mutexes we can enter: if we know that apix may be
 * holding a spinlock when it calls into us, then we must avoid blocking on an
 * adaptive mutex to avoid deadlock, not to mention avoiding other kinds of
 * blocking behavior, such as memory allocation with `KM_SLEEP`.  Thus again,
 * our high priority locks.
 *
 * The mutexes that we define and use, the granularity of the objects they
 * guard, and what they protect, are:
 *
 * - `ais_lock`.  A segment-wide mutex that serializes access
 *   to the segment's list of IRTs and the interrupt remapping fields of DTEs
 *   (e.g., when an IRT is added via `intrmap_segment_add_irt`).
 * - `aiirt_alloc_lock`.  A per-IRT mutex that serializes allocation of IRTEs
 *   and their cookies.
 * - `aicb_lock`.  Serializes access to an IOMMU's command buffer.  One per
 *   IOMMU.
 * - `aiel_lock`.  Serializes access to each IOMMU's event log.  One per IOMMU.
 * - `ai_ctl_lock`.  Serializes access to each IOMMU's Control register.  One
 *   per IOMMU.
 *
 * The Status register is accessed unlocked, as reading it induces no side
 * effects, and each write only sets the write-1-to-clear bits specific to a
 * given consumer.
 *
 * Locks are acquired in this order:
 *
 * OPAQUE TO US:
 *  0. apix_lock
 *  1. apic_ioapic_lock
 * OUR LOCKS:
 *  2. ais_lock or aiirt_alloc_lock
 *  3. aicb_lock or aiel_lock
 *  4. ai_ctl_lock (if accessing the control register)
 * ZEN FABRIC LOCKS:
 *  5. zi_smn_lock (when accessing SMN registers)
 *
 * Nothing holds the locks of more than one IRT or IOMMU simultaneously.
 *
 * Present Status and Future Directions in the Oxide Architecture
 * --------------------------------------------------------------
 * The Oxide architecture supports enabling interrupt remapping via the AMD
 * IOMMU.  Page remapping for devices is not presently implemented or planned.
 *
 * Currently, as with interrupt remapping for the Intel IOMMU, the code that
 * implements this hangs off of the root nexus driver (`rootnex`); we do not
 * currently ship a discrete `amd_iommu` module, though we plan to introduce
 * one and subsume.  We currently do not generate interrupts from the IOMMU,
 * either: we poll the status of each command as we send it, and poll the
 * event log immediately after to detect errors.
 *
 * ### Future Work
 *
 * Part of this design shape is forced by the Intel IOMMU, which is inherently
 * tied into `rootnex` in a similar way.  We have done some preliminary work to
 * abstract between the two types of parts, but there is more to do.  Ideally,
 * we would like a PSM-like abstraction to accommodate the two, but that
 * infrastructure is currently specific to interrupt controllers, and should be
 * generalized before we attempt to incorporate IOMMUs into the framework.
 *
 * Work is also currently underway to provide drivers and generalized device
 * support for other IP in the Zen architectural taxonomy; for example NBIO, DF,
 * and IOMS objects.  Since IOMMUs architecturally slot into IOMS/IOHC support,
 * the intent is to introduce a proper `amd_iommu` module that nests under
 * these, with an instance per IOMMU present in the system.  We will also
 * support interrupt generation for asynchronous command completion and event
 * log handling at that time.
 *
 * The IOMMU has a notion of a "segmented device table", that lets us allocate
 * a smaller set of device tables, not shared across all IOMMUs, but rather,
 * specific to the set of devices "downstream" of a particular IOMMU.  Not only
 * would this save memory, but it would eliminate concerns about cross-IOMMU
 * caching, facilitating more targeted invalidations when device in-memory
 * structures are updated.
 *
 * Finally, we should integrate event logs into the FM framework, generating
 * ereports and notifications to drivers for handling faults.  The architectural
 * driver work is requisite to properly support this.
 */

